# int -- whole numbers

x = 10
y=-5

big = 1_000_000 # under scores for readability

print(big)

# float - decimal numbers
pi = 3.14

temp = -2.5

sci = 1.5e3 # scientific notation = 1500.0

# Arithmetic Operators
print(10 + 3)    # 13  — addition
print(10 - 3)    # 7   — subtraction
print(10 * 3)    # 30  — multiplication
print(10 / 3)    # 3.33 — division (always float)
print(10 // 3)   # 3   — floor division
print(10 % 3)    # 1   — modulus (remainder)
print(10 ** 3)   # 1000 — exponent

# Type conversion
print(int(4.5)) # so the output is in integer now
print(float(5)) # 5.0

print(str(50)) # output is in string like "100"
